import { TABLE_Z } from './layout'

/**
 * Ключевые кадры камеры. Индекс = значение `data-cam` у маркера в вёрстке.
 *
 * Маршрут повторяет настоящий путь гостя (план — в layout.ts): аллея
 * парка → площадь с буквами LOFT PARK → вход на террасу под деревьями →
 * зал со стеной из мха → белый шатёр → подъём над парком.
 *
 * Отрезки между кадрами проверены на проходимость: камера идёт через
 * проход в кашпо (x ∈ [−2, 2]), через открытый проём зала (x ∈ [−7, 7])
 * и не задевает стволы деревьев. Сдвигая кадр, проверяйте прямую между
 * соседними кадрами против TREES и стен.
 *
 * Помимо позиции кадр несёт «погоду»: туман, его цвет и силу bloom.
 */
export type Keyframe = {
  pos: [number, number, number]
  look: [number, number, number]
  fog: number
  fogColor: string
  bloom: number
  fov: number
  /**
   * Ракурс для вертикального экрана. Кадры выстроены под 16:9, а в портрете
   * по горизонтали влезает втрое меньше: без этого на телефоне от букв
   * LOFT PARK оставалось одно «LOFT». CameraRig смешивает по пропорции экрана.
   */
  portrait?: { pos: [number, number, number]; look: [number, number, number] }
}

const dish = (x: number): Keyframe => ({
  // Взгляд смещён влево на 0.8 — блюдо встаёт в правую половину экрана
  pos: [x - 0.8, 2.05, TABLE_Z + 2.8],
  look: [x - 0.8, 1.15, TABLE_Z],
  fog: 0.012,
  fogColor: '#1a100a',
  bloom: 0.9,
  fov: 42,
  // в портрете блюдо по центру: текст там сверху, а не слева
  portrait: { pos: [x, 2.25, TABLE_Z + 3.1], look: [x, 1.1, TABLE_Z] },
})

