/**
 * Ключевые кадры камеры. Индекс = значение `data-cam` у маркера в вёрстке.
 *
 * Маршрут повторяет настоящий путь гостя (план — в layout.ts): аллея
 * парка → площадь с буквами LOFT PARK → вход на террасу под деревьями →
 * зал со стеной из мха → белый шатёр → подъём над парком.
 *
 * Отрезки между кадрами проверены на проходимость: камера идёт через
 * проход в кашпо (x ∈ [−2, 2]), через открытый проём зала (x ∈ [−7, 7])
 * и не задевает стволы деревьев. Сдвигая кадр, проверяйте прямую между
 * соседними кадрами против TREES и стен.
 *
 * Помимо позиции кадр несёт «погоду»: туман, его цвет и силу bloom.
 */
export type Keyframe = {
  pos: [number, number, number]
  look: [number, number, number]
  fog: number
  fogColor: string
  bloom: number
  fov: number
}

